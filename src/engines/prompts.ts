export function buildUserPrompt(scene: Scene, input: string, refs: { n: number; title: string; excerpt: string }[]) {
  const refText = refs.length ? `\n\n【参考资料】（仅可引用以下序号）\n${refs.map(r => `[${r.n}] ${r.title}：${r.excerpt}`).join('\n')}` : ''
  return `${TASKS[scene]}${refText}\n\n【用户输入】\n${input}`
}
