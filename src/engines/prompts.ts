/** 生成后的边界自检：发现定性、量纪类表述时追加提醒。 */
export function boundaryCheck(text: string) {
  const hits = [...new Set(text.match(/(?<![不未])构成[^，。、]{0,6}(违纪|违法|犯罪)|应(当)?给予[^，。]{0,8}处分|建议(给予|开除|撤销|移送)/g) || [])]
  return hits
}

