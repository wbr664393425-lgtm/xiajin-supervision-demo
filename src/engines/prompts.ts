export function materialPrompt(type: string, cases: { title: string; fact: string; result: string; lesson: string; area: string }[], theme: string, audience: string) {
  return [`请撰写《${type}》初稿。`, MATERIAL_GUIDE[type] || '', `主题：${theme || '守纪律 讲规矩 筑牢廉洁防线'}`, `受众：${audience}`, '', '【所选案例】', ...cases.map((c, i) => `${i + 1}. ${c.title}（${c.area}）\n基本案情：${c.fact}\n处理结果：${c.result}\n警示要点：${c.lesson}`)].join('\n')
}
/** 去掉模型偶尔输出的 Markdown 标记，保持公文排版 */
export const stripMarkdown = (t: string) => t.replace(/^#{1,6}\s*/gm, '').replace(/\*\*(.+?)\*\*/g, '$1').replace(/^\s*[-*]\s+/gm, '')
